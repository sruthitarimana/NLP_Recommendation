# Convert them into lower case
df["Skills"]= df["Skills"].str.lower()
print(df)

# TF-IDF
from sklearn.feature_extraction.text import TfidfVectorizer
tfidf = TfidfVectorizer()
skill_vectors = tfidf.fit_transform(df["Skills"])
print(skill_vectors.toarray())

tfidf_table = pd.DataFrame(skill_vectors.toarray(), columns=tfidf.get_feature_names_out())
print(tfidf_table)

# cosine-Similarity
from sklearn.metrics.pairwise import cosine_similarity
similarity_matrix = cosine_similarity(skill_vectors)
print(similarity_matrix)

similarity_df= pd.DataFrame(similarity_matrix, columns=df["Name"], index=df["Name"])
print(similarity_df)

similarity_percentage = similarity_df*100
similarity_percentage.round(2)

selected_name = "Bilal"

scores = similarity_df.loc[selected_name]
scores = scores.drop(selected_name)
top_matches = scores.sort_values(ascending=False).head(3)
top_matches = top_matches*100
print(top_matches)

# Create the recommendation function
def recommended_profiles(person_name, number_of_matches=3):

  # check whetehr the person exists
  if person_name not in df["Name"].values:
    print(f"{person_name} not found in the dataset")
    return

  # Get the selected person's similarity Score
  scores = similarity_df.loc[person_name]

  # Drop the selected person's own profile from the list
  scores = scores.drop(person_name)

  #Sort and select the top matches
  top_matches = scores.sort_values(ascending=False).head(number_of_matches)
  top_matches = top_matches*100

  print(f"Top {number_of_matches} matches for {person_name}:")
  for name, score in top_matches.items():
    print(f"{name}: {score:.2f}%")

recommended_profiles("Bilal", 5)

